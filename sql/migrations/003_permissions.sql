-- ChronosDB least-privilege roles (Phase 15G / Phase 10D)
-- Role creation requires SECADM. The migration runner reports failures
-- without hiding them, so restricted environments can review the message.

CREATE ROLE READ_ONLY_APP;
CREATE ROLE SIMULATION_WRITER;
CREATE ROLE AUDIT_WRITER;
CREATE ROLE ADMIN_MIGRATION;

GRANT SELECT ON SUPPLY_CHAIN.SUPPLIERS TO READ_ONLY_APP;
GRANT SELECT ON SUPPLY_CHAIN.COMPONENTS TO READ_ONLY_APP;
GRANT SELECT ON SUPPLY_CHAIN.INVENTORY TO READ_ONLY_APP;
GRANT SELECT ON SUPPLY_CHAIN.PURCHASE_ORDERS TO READ_ONLY_APP;
GRANT SELECT ON SUPPLY_CHAIN.CUSTOMER_ORDERS TO READ_ONLY_APP;
GRANT SELECT ON SUPPLY_CHAIN.PRODUCTION_ORDERS TO READ_ONLY_APP;
GRANT SELECT ON SUPPLY_CHAIN.DISRUPTION_EVENTS TO READ_ONLY_APP;
GRANT SELECT ON SUPPLY_CHAIN.SCENARIOS TO READ_ONLY_APP;
GRANT SELECT ON SIMULATION.RESULTS TO READ_ONLY_APP;
GRANT SELECT ON OPTIMIZATION.RECOMMENDATIONS TO READ_ONLY_APP;
GRANT SELECT ON EVIDENCE.DOCUMENTS TO READ_ONLY_APP;
GRANT SELECT ON EVIDENCE.CHUNKS TO READ_ONLY_APP;
GRANT SELECT ON AUDIT.DECISION_LEDGER TO READ_ONLY_APP;

GRANT SELECT, INSERT, UPDATE ON SIMULATION.OVERLAYS TO SIMULATION_WRITER;
GRANT SELECT, INSERT, UPDATE ON SIMULATION.RESULTS TO SIMULATION_WRITER;
GRANT SELECT ON SUPPLY_CHAIN.INVENTORY TO SIMULATION_WRITER;
GRANT SELECT ON SUPPLY_CHAIN.PURCHASE_ORDERS TO SIMULATION_WRITER;
GRANT SELECT ON OPTIMIZATION.RECOMMENDATIONS TO SIMULATION_WRITER;

GRANT INSERT ON AUDIT.DECISION_LEDGER TO AUDIT_WRITER;
GRANT INSERT ON AUDIT.REPLAY_EVENTS TO AUDIT_WRITER;
GRANT SELECT ON AUDIT.DECISION_LEDGER TO AUDIT_WRITER;
GRANT SELECT ON AUDIT.REPLAY_EVENTS TO AUDIT_WRITER;

GRANT ALL PRIVILEGES ON SCHEMA SUPPLY_CHAIN TO ADMIN_MIGRATION WITH GRANT OPTION;
GRANT ALL PRIVILEGES ON SCHEMA SIMULATION TO ADMIN_MIGRATION WITH GRANT OPTION;
GRANT ALL PRIVILEGES ON SCHEMA OPTIMIZATION TO ADMIN_MIGRATION WITH GRANT OPTION;
GRANT ALL PRIVILEGES ON SCHEMA EVIDENCE TO ADMIN_MIGRATION WITH GRANT OPTION;
GRANT ALL PRIVILEGES ON SCHEMA AUDIT TO ADMIN_MIGRATION WITH GRANT OPTION;
