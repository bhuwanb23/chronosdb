-- ChronosDB core schema (Phase 15G)
-- Run these migrations against a fresh database. Rerunning against an existing
-- schema will report "already exists" errors; reset the volume first.

CREATE SCHEMA SUPPLY_CHAIN;
CREATE SCHEMA SIMULATION;
CREATE SCHEMA OPTIMIZATION;
CREATE SCHEMA EVIDENCE;
CREATE SCHEMA AUDIT;

CREATE TABLE SUPPLY_CHAIN.SUPPLIERS (
    SUPPLIER_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    NAME VARCHAR(256) NOT NULL,
    COUNTRY VARCHAR(64),
    REGION VARCHAR(64),
    STATUS VARCHAR(32),
    SUPPLIER_CLASS VARCHAR(64),
    APPROVAL_STATUS VARCHAR(32),
    EFFECTIVE_FROM TIMESTAMP,
    EFFECTIVE_TO TIMESTAMP
);

CREATE TABLE SUPPLY_CHAIN.COMPONENTS (
    COMPONENT_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    NAME VARCHAR(256) NOT NULL,
    COMPONENT_TYPE VARCHAR(64),
    CRITICALITY VARCHAR(32),
    SOURCE_CLASS VARCHAR(64),
    STATUS VARCHAR(32),
    UNIT VARCHAR(16),
    SAFETY_STOCK_UNITS DECIMAL(18,3),
    STANDARD_UNIT_COST_INR DECIMAL(18,2)
);

CREATE TABLE SUPPLY_CHAIN.WAREHOUSES (
    WAREHOUSE_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    NAME VARCHAR(256),
    FACILITY_ID VARCHAR(64),
    REGION VARCHAR(64)
);

CREATE TABLE SUPPLY_CHAIN.INVENTORY (
    INVENTORY_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    COMPONENT_ID VARCHAR(64) NOT NULL,
    WAREHOUSE_ID VARCHAR(64) NOT NULL,
    ON_HAND_QUANTITY DECIMAL(18,3) NOT NULL DEFAULT 0,
    RESERVED_QUANTITY DECIMAL(18,3) NOT NULL DEFAULT 0,
    QUARANTINED_QUANTITY DECIMAL(18,3) NOT NULL DEFAULT 0,
    SAFETY_STOCK_QUANTITY DECIMAL(18,3) NOT NULL DEFAULT 0,
    SNAPSHOT_TIME TIMESTAMP
);

CREATE TABLE SUPPLY_CHAIN.PURCHASE_ORDERS (
    PURCHASE_ORDER_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    SUPPLIER_ID VARCHAR(64) NOT NULL,
    COMPONENT_ID VARCHAR(64) NOT NULL,
    DESTINATION_WAREHOUSE_ID VARCHAR(64),
    ORDERED_QUANTITY DECIMAL(18,3),
    RECEIVED_QUANTITY DECIMAL(18,3),
    OUTSTANDING_QUANTITY DECIMAL(18,3),
    UNIT_COST_INR DECIMAL(18,2),
    CURRENCY VARCHAR(8),
    STATUS VARCHAR(32),
    ORDER_TIME TIMESTAMP,
    EXPECTED_ARRIVAL_TIME TIMESTAMP,
    ACTUAL_ARRIVAL_TIME TIMESTAMP,
    EXPEDITE_ELIGIBLE SMALLINT DEFAULT 0
);

CREATE TABLE SUPPLY_CHAIN.CUSTOMER_ORDERS (
    CUSTOMER_ORDER_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    CUSTOMER_ID VARCHAR(64) NOT NULL,
    PRIORITY VARCHAR(32),
    SLA_CLASS VARCHAR(32),
    STATUS VARCHAR(32),
    CURRENCY VARCHAR(8),
    ORDER_TIME TIMESTAMP,
    PROMISED_DELIVERY_TIME TIMESTAMP
);

CREATE TABLE SUPPLY_CHAIN.PRODUCTION_ORDERS (
    PRODUCTION_ORDER_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    PRODUCT_ID VARCHAR(64),
    FACILITY_ID VARCHAR(64),
    BATCH_SIZE DECIMAL(18,3),
    PLANNED_QUANTITY DECIMAL(18,3),
    COMPLETED_QUANTITY DECIMAL(18,3),
    PRIORITY VARCHAR(32),
    STATUS VARCHAR(32),
    PLANNED_START_TIME TIMESTAMP,
    PLANNED_COMPLETION_TIME TIMESTAMP,
    ACTUAL_START_TIME TIMESTAMP,
    ACTUAL_COMPLETION_TIME TIMESTAMP
);

CREATE TABLE SUPPLY_CHAIN.DISRUPTION_EVENTS (
    DISRUPTION_EVENT_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    SUPPLIER_ID VARCHAR(64),
    EVENT_TYPE VARCHAR(64),
    SEVERITY VARCHAR(32),
    SCOPE_TYPE VARCHAR(64),
    STATUS VARCHAR(32),
    START_TIME TIMESTAMP,
    REPORTED_TIME TIMESTAMP,
    EXPECTED_END_TIME TIMESTAMP,
    PROJECTED_ARRIVAL_TIME TIMESTAMP,
    RECOVERY_LAG_HOURS INTEGER
);

CREATE TABLE SUPPLY_CHAIN.SCENARIOS (
    SCENARIO_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    NAME VARCHAR(256),
    AS_OF_TIME TIMESTAMP,
    DISRUPTION_EVENT_ID VARCHAR(64),
    SUPPLIER_ID VARCHAR(64),
    COMPONENT_ID VARCHAR(64),
    PURCHASE_ORDER_ID VARCHAR(64),
    STATUS VARCHAR(32),
    PAYLOAD CLOB
);

CREATE TABLE SIMULATION.OVERLAYS (
    OVERLAY_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    SCENARIO_ID VARCHAR(64) NOT NULL,
    INTERVENTION_TYPE VARCHAR(64) NOT NULL,
    PARAMETERS CLOB,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE SIMULATION.RESULTS (
    SIMULATION_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    SCENARIO_ID VARCHAR(64) NOT NULL,
    OVERLAY_ID VARCHAR(64),
    RESULT_PAYLOAD CLOB,
    OVERLAY_FIDELITY DECIMAL(6,4),
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE OPTIMIZATION.RECOMMENDATIONS (
    RECOMMENDATION_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    SCENARIO_ID VARCHAR(64) NOT NULL,
    PLAN_ID VARCHAR(64) NOT NULL,
    UTILITY_SCORE DECIMAL(6,4),
    HARD_CONSTRAINTS_SATISFIED SMALLINT DEFAULT 0,
    RECOMMENDATION_PAYLOAD CLOB,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE EVIDENCE.DOCUMENTS (
    DOCUMENT_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    TITLE VARCHAR(512),
    DOCUMENT_TYPE VARCHAR(64),
    SOURCE_PATH VARCHAR(1024),
    CONTENT CLOB,
    ACCESS_LABEL VARCHAR(64),
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE EVIDENCE.CHUNKS (
    CHUNK_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    DOCUMENT_ID VARCHAR(64) NOT NULL,
    CHUNK_INDEX INTEGER NOT NULL,
    CHUNK_TEXT CLOB NOT NULL,
    METADATA CLOB
);

CREATE TABLE EVIDENCE.EMBEDDINGS (
    EMBEDDING_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    CHUNK_ID VARCHAR(64) NOT NULL,
    MODEL_NAME VARCHAR(128) NOT NULL,
    DIMENSION INTEGER NOT NULL,
    EMBEDDING BLOB NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE AUDIT.DECISION_LEDGER (
    DECISION_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    SCENARIO_ID VARCHAR(64) NOT NULL,
    RECOMMENDATION_ID VARCHAR(64),
    DECISION_PAYLOAD CLOB NOT NULL,
    LEDGER_HASH VARCHAR(128) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE AUDIT.REPLAY_EVENTS (
    REPLAY_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    DECISION_ID VARCHAR(64) NOT NULL,
    REPLAY_PAYLOAD CLOB NOT NULL,
    REPLAY_INTEGRITY DECIMAL(6,4),
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE SYSTEM_HEALTH (
    CHECK_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    COMPONENT VARCHAR(64) NOT NULL,
    STATUS VARCHAR(16) NOT NULL,
    CHECKED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    DETAILS VARCHAR(512),
    CONSTRAINT SYSTEM_HEALTH_STATUS_CK CHECK (STATUS IN ('pass', 'fail', 'degraded'))
);
