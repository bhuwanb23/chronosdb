-- ChronosDB evidence vectors (Phase 15G / Phase 15I)
-- Embeddings are stored as BLOB plus an explicit dimension so the same
-- migration works on Db2 releases without native VECTOR support.

CREATE TABLE EVIDENCE.EMBEDDING_INDEX (
    INDEX_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    EMBEDDING_ID VARCHAR(64) NOT NULL,
    DOCUMENT_ID VARCHAR(64) NOT NULL,
    CHUNK_ID VARCHAR(64) NOT NULL,
    MODEL_NAME VARCHAR(128) NOT NULL,
    DIMENSION INTEGER NOT NULL,
    NORM DOUBLE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

CREATE INDEX IDX_EMBEDDING_INDEX_DOCUMENT
    ON EVIDENCE.EMBEDDING_INDEX (DOCUMENT_ID);
CREATE INDEX IDX_EMBEDDING_INDEX_MODEL
    ON EVIDENCE.EMBEDDING_INDEX (MODEL_NAME);
